//! The search parameters a tuning run varies: the pruning, reduction and
//! extension constants that shape the tree, the history updates and move
//! scores that order it, and the coefficients of the time allocation that
//! decide how long a search runs, each named once here and read through
//! `Param::get` wherever the search uses it.
//!
//! The values are not written here. The build reads them from an SPSA settings
//! file, one `name = value` line per parameter registered below: the file the
//! `YORKIE_SPSA_CONFIG` environment variable names, or the one the engine
//! config's `spsa_config` key names. `configs/spsa/yaneuraou.toml` holds the
//! values with which the search agrees node for node with YaneuraOu, and
//! `configs/spsa/yorkie.toml` the values the engine plays with.
//!
//! Every parameter is an integer. A coefficient the arithmetic uses as a
//! floating-point number is registered scaled by a power of ten and read
//! through `Param::scaled`: the value divided by its scale is the correctly
//! rounded quotient, which is the same `f64` the decimal literal of the
//! unscaled value spells, so YaneuraOu's value allocates bit for bit as its
//! literal does.
//!
//! A parameter is a `const`, and `get` on it is the constant: the search
//! compiles to what a literal at the use site would give. A different value is
//! a different build.
//!
//! Each parameter carries the range of values the search tolerates: the
//! arithmetic it enters stays inside `i32` over the whole depth range, and the
//! invariant the code around it relies on still holds. That range is wider than
//! any range worth tuning over; it only keeps a mistyped value from producing a
//! search that hangs or overflows. The build script reads the ranges and the
//! names from the registry below and refuses a settings file outside them.

/// One search parameter, a compile-time constant.
#[derive(Clone, Copy)]
pub(crate) struct Param(i32);

impl Param {
    const fn new(value: i32) -> Self {
        Self(value)
    }

    #[inline(always)]
    pub(crate) const fn get(self) -> i32 {
        self.0
    }

    /// The value divided by `scale`, for a coefficient registered scaled.
    #[inline(always)]
    pub(crate) fn scaled(self, scale: f64) -> f64 {
        f64::from(self.0) / scale
    }
}

/// The value of every registered parameter, one `const` of the parameter's own
/// name each, generated by the build script from the SPSA settings file the
/// build selects. The build script has checked every value against the range
/// below; the assertion each parameter carries checks it again.
pub(crate) mod values {
    include!(concat!(env!("OUT_DIR"), "/spsa_values.rs"));
}

/// Each entry registers one parameter: the constant's name, the parameter's key
/// in an SPSA settings file as a byte string, and the values the search
/// tolerates. The build script reads the keys and the ranges from this text.
macro_rules! search_params {
    ($(
        $(#[doc = $doc:literal])*
        $id:ident = $name:literal, $min:literal..=$max:literal;
    )+) => {
        $(
            $(#[doc = $doc])*
            pub(crate) const $id: Param = Param::new(values::$id);
            const _: () = assert!($min <= values::$id && values::$id <= $max);
            // The read the search makes, evaluated where only a compile-time
            // constant is accepted: the build fails if a parameter is not one.
            const _: i32 = $id.get();
        )+
    };
}

